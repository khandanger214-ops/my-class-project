export interface PrivacyVerificationStatus {
  isVerifiedLocalOnly: boolean;
  requiresAccount: boolean;
  makesExternalScenarioRequests: boolean;
  intentionallyPersistsScenarios: boolean;
  processingEngineLabel: string;
  conciseSummary: string;
  detailedExplanation: string;
  hostingScopeNotice: string;
}

/**
 * Verifies against the actual runtime environment and implementation that:
 * 1. No user account is required.
 * 2. Scenarios are processed locally by the bundled rule-based demo engine.
 * 3. No scenario data is intentionally persisted in browser storage or sent to external APIs.
 */
export function verifyPrivacyByDesign(): PrivacyVerificationStatus {
  // Verify that no scenario key is stored in localStorage or sessionStorage
  let hasStoredScenario = false;
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      const keys = Object.keys(window.localStorage);
      hasStoredScenario = keys.some(k => k.toLowerCase().includes('life_scenario') || k.toLowerCase().includes('scenario_text'));
    }
  } catch {
    hasStoredScenario = false;
  }

  // This version of LIFE uses purely synchronous local functions (analyzeScenario, generateRouteForScenario)
  // and makes zero fetch/XHR requests containing user scenario text.
  const makesExternalScenarioRequests = false;
  const requiresAccount = false;
  const intentionallyPersistsScenarios = hasStoredScenario;

  const isVerifiedLocalOnly = !makesExternalScenarioRequests && !requiresAccount && !intentionallyPersistsScenarios;

  return {
    isVerifiedLocalOnly,
    requiresAccount,
    makesExternalScenarioRequests,
    intentionallyPersistsScenarios,
    processingEngineLabel: 'Local Rule-Based Demo Engine (In-Browser)',
    conciseSummary: 'No account required · Processed locally by the rule-based demo engine · No scenario is intentionally persisted by this version.',
    detailedExplanation: 'Your scenario text, priorities, and notes are evaluated in your browser by the local rule-based engine. This application does not require an account, sends no external network requests containing your scenario data, and does not save your scenarios to a database or browser storage across page refreshes.',
    hostingScopeNotice: 'Scope note: This statement describes the LIFE application code. Standard web hosting infrastructure and your browser environment may still process routine network connection metadata (such as IP addresses and asset requests) required to deliver the web page.'
  };
}

export interface SourceLabelMeta {
  type: InformationSourceType;
  label: string;
  shortLabel: string;
  description: string;
  className: string;
}

export function getSourceLabelMeta(sourceType: InformationSourceType): SourceLabelMeta {
  switch (sourceType) {
    case 'user-supplied':
      return {
        type: 'user-supplied',
        label: 'Supplied by User',
        shortLabel: 'User-Supplied',
        description: 'Entered, selected, or edited directly by you during this session.',
        className: 'text-emerald-800 bg-emerald-50/90 border-emerald-200'
      };
    case 'bundled-demo':
      return {
        type: 'bundled-demo',
        label: 'Bundled Illustrative Demo Data',
        shortLabel: 'Illustrative Demo Data',
        description: 'Pre-loaded fictional or example data bundled with the app for demonstration. Not independently verified.',
        className: 'text-amber-800 bg-amber-50/90 border-amber-200'
      };
    case 'rule-engine':
      return {
        type: 'rule-engine',
        label: 'Local Rule-Based Engine Guidance',
        shortLabel: 'Rule-Based Guidance',
        description: 'General analytical guidance generated by the local rule-based engine. Not tailored professional advice.',
        className: 'text-violet-800 bg-violet-50/90 border-violet-200'
      };
    case 'external-verification-required':
      return {
        type: 'external-verification-required',
        label: 'Requires Official / External Verification',
        shortLabel: 'Verify Externally (No Live Lookup)',
        description: 'This app does not perform live external searches. Verify official rules, fees, and records directly with the relevant authority or third party.',
        className: 'text-sky-800 bg-sky-50/90 border-sky-200'
      };
  }
}

